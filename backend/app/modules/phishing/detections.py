"""Detection content generation per campaign: IOC lists, URL regex, Sigma (proxy + email) and YARA (kit HTML)."""
from __future__ import annotations

import re
import uuid
from collections import Counter
from datetime import datetime, timezone
from typing import Any
from urllib.parse import urlparse

SIGMA_NS = uuid.UUID("5d2f3c1e-8a0a-4a2d-9d1e-7b6c0f0c2b11")


def _yaml_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def _rx_escape_path(path: str) -> str:
    """Generalise one URL path: random tokens -> [A-Za-z0-9]{n,}, digits -> \\d+."""
    parts = []
    for seg in path.split("/"):
        if not seg:
            parts.append("")
        elif re.fullmatch(r"[A-Za-z0-9]{12,}", seg):
            parts.append(f"[A-Za-z0-9]{{{max(8, len(seg) - 6)},}}")
        elif re.fullmatch(r"\d+", seg):
            parts.append(r"\d+")
        else:
            parts.append(re.escape(seg).replace(r"\-", "-"))
    return "/".join(parts)


def url_regex(urls: list[str]) -> str:
    paths = Counter((urlparse(u).path or "/") for u in urls)
    common = [p for p, _ in paths.most_common(5) if p not in ("/", "")]
    alts = sorted({_rx_escape_path(p) for p in common})[:5]
    if not alts:
        return r"^https?://[^/]+/?(\?.*)?$"
    return r"^https?://[^/]+(" + "|".join(alts) + r")(\?.*)?$"


def generalize_hosts(domains: list[str]) -> list[str]:
    """Keyword stems shared by lookalike domains (e.g. 'paypal', 'secure-login')."""
    stems: Counter[str] = Counter()
    for d in domains:
        label = d.split(".")[0]
        for tok in re.split(r"[-_\d]+", label):
            if len(tok) >= 5:
                stems[tok.lower()] += 1
    return [s for s, n in stems.most_common(6) if n >= 2]


def sigma_proxy(camp: dict[str, Any], domains: list[str], rx: str, stems: list[str]) -> str:
    rid = uuid.uuid5(SIGMA_NS, f"proxy:{camp['name']}")
    dom_lines = "\n".join(f"      - {_yaml_str(d)}" for d in sorted(domains)[:50])
    stem_block = ""
    if stems:
        stem_block = "  selection_lookalike:\n    cs-host|contains:\n" + "\n".join(f"      - {_yaml_str(s)}" for s in stems) + \
                     "\n    c-uri|re: " + _yaml_str(rx) + "\n"
    cond = "selection_domain or selection_lookalike" if stems else "selection_domain"
    return f"""title: Phishing campaign {camp['name']} - {camp.get('brand') or 'unknown brand'} lure infrastructure
id: {rid}
status: experimental
description: Web proxy requests to domains attributed to phishing campaign {camp['name']} ({camp.get('kit_name') or 'kit unknown'}). Generated by CTI Ops P4 pipeline from {camp.get('sample_count', 0)} captured pages.
references:
    - https://urlscan.io/search/#task.tags%3Aphishing
author: CTI Ops P4 pipeline
date: {datetime.now(timezone.utc).strftime('%Y/%m/%d')}
tags:
    - attack.initial_access
    - attack.t1566.002
    - attack.credential_access
    - attack.t1556
logsource:
    category: proxy
detection:
  selection_domain:
    cs-host:
{dom_lines}
{stem_block}  condition: {cond}
falsepositives:
    - Security research or sandbox traffic to the same hosts
    - Lookalike stems may match legitimate marketing domains; review before blocking
level: high
"""


def sigma_email(camp: dict[str, Any], domains: list[str], stems: list[str]) -> str:
    rid = uuid.uuid5(SIGMA_NS, f"email:{camp['name']}")
    dom_lines = "\n".join(f"      - {_yaml_str(d)}" for d in sorted(domains)[:50])
    subj = ""
    if camp.get("title_examples"):
        subj = "  selection_subject:\n    Subject|contains:\n" + "\n".join(
            f"      - {_yaml_str(t[:60])}" for t in camp["title_examples"][:4]) + "\n"
    cond = "selection_url" + (" or (selection_subject and selection_brand)" if subj and camp.get("brand") else "")
    brand = ""
    if subj and camp.get("brand"):
        brand = f"  selection_brand:\n    Body|contains: {_yaml_str(camp['brand'])}\n"
    return f"""title: Phishing email delivering campaign {camp['name']} ({camp.get('brand') or 'unknown brand'})
id: {rid}
status: experimental
description: Inbound email containing links to infrastructure of phishing campaign {camp['name']}. Field names follow the generic email log model (Url, Subject, Body); map to your gateway's schema.
author: CTI Ops P4 pipeline
date: {datetime.now(timezone.utc).strftime('%Y/%m/%d')}
tags:
    - attack.initial_access
    - attack.t1566.002
logsource:
    category: email
detection:
  selection_url:
    Url|contains:
{dom_lines}
{subj}{brand}  condition: {cond}
falsepositives:
    - Newsletters quoting the lure page title
level: high
"""


def _yara_id(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def yara_rule(camp: dict[str, Any], strings: list[str], kit: dict[str, Any] | None) -> str | None:
    strs = []
    for s in strings:
        s = s.strip()
        if 4 <= len(s) <= 120 and not re.search(r'[\\"\n\r]', s):
            strs.append(s)
    strs = list(dict.fromkeys(strs))[:12]
    if len(strs) < 2:
        return None
    body = "\n".join(f'        $s{i} = "{s}" ascii wide nocase' for i, s in enumerate(strs, 1))
    need = 2 if len(strs) < 4 else 3
    kit_line = f"        kit = \"{kit['name']}\"\n" if kit else ""
    return f"""rule phish_{_yara_id(camp['name'])}_{_yara_id((camp.get('brand') or 'generic').lower())}
{{
    meta:
        description = "HTML of phishing campaign {camp['name']} impersonating {camp.get('brand') or 'unknown brand'}"
        author = "CTI Ops P4 pipeline"
        date = "{datetime.now(timezone.utc).strftime('%Y-%m-%d')}"
        samples = {camp.get('sample_count', 0)}
{kit_line}    strings:
{body}
    condition:
        filesize < 3MB and {need} of ($s*)
}}
"""


def yara_strings_from(members_features: list[dict[str, Any]], n: int) -> list[str]:
    """Strings shared by at least half of the cluster: form input names, external script/form hosts, exfil endpoints,
    distinctive image names, titles."""
    cnt: Counter[str] = Counter()
    for f in members_features:
        seen = set()
        for name in f.get("input_names", []):
            if len(name) >= 5:
                seen.add(f'name="{name}"')
        for h in f.get("script_hosts", []):
            if not re.search(r"(googleapis|gstatic|cloudflare|jsdelivr|jquery|bootstrap|fontawesome|unpkg)", h):
                seen.add(h)
        for e in f.get("exfil", []):
            if e["type"] in ("discord_webhook", "form_service", "form_action", "firebase"):
                seen.add(e["value"][:100])
        for img in f.get("image_names", []):
            if len(img) >= 8 and not re.fullmatch(r"[a-f0-9]{16,}\.\w+", img):
                seen.add(img)
        if f.get("title") and len(f["title"]) >= 8:
            seen.add(f["title"][:80])
        for s in seen:
            cnt[s] += 1
    need = max(1, n // 2)
    return [s for s, c in cnt.most_common(40) if c >= need]


def build_detections(camp: dict[str, Any], members: list[dict[str, Any]], kit: dict[str, Any] | None) -> list[dict[str, Any]]:
    """members: dicts with url, domain, apex_domain, ip, features. Returns Detection row dicts (without campaign_id)."""
    urls = [m["url"] for m in members]
    domains = sorted({m["domain"] for m in members if m.get("domain")})
    apexes = sorted({m["apex_domain"] for m in members if m.get("apex_domain")})
    ips = sorted({m["ip"] for m in members if m.get("ip")})
    rx = url_regex(urls)
    stems = generalize_hosts(domains)
    conf = "high" if camp.get("sample_count", 0) >= 3 and camp.get("cohesion", 0) >= 0.6 else "medium"
    shared_hosting = {"vercel.app", "netlify.app", "pages.dev", "web.app", "firebaseapp.com", "github.io", "weebly.com",
                      "blogspot.com", "wixsite.com", "glitch.me", "repl.co", "workers.dev", "r2.dev", "edgeone.dev",
                      "webflow.io", "godaddysites.com", "000webhostapp.com", "surge.sh", "ngrok-free.app", "trycloudflare.com"}
    fp_domains = "Includes shared-hosting apex domains; block the full hostname, not the apex." if any(a in shared_hosting for a in apexes) else None
    out = [
        {"type": "ioc_domain", "target": "web_gateway", "title": f"{camp['name']} hostnames", "content": "\n".join(domains),
         "confidence": "high", "false_positive_notes": fp_domains},
        {"type": "ioc_url", "target": "mail_gateway", "title": f"{camp['name']} lure URLs", "content": "\n".join(sorted(urls)),
         "confidence": "high", "false_positive_notes": None},
        {"type": "url_regex", "target": "web_gateway", "title": f"{camp['name']} URL path pattern", "content": rx,
         "confidence": conf, "false_positive_notes": "Path pattern only; pair with hostname stems or reputation."},
        {"type": "sigma", "target": "web_gateway", "title": f"Sigma (proxy): {camp['name']}",
         "content": sigma_proxy(camp, domains, rx, stems), "confidence": conf,
         "false_positive_notes": "Lookalike stems can match legitimate domains." if stems else None},
        {"type": "sigma", "target": "mail_gateway", "title": f"Sigma (email): {camp['name']}",
         "content": sigma_email(camp, domains, stems), "confidence": conf, "false_positive_notes": None},
    ]
    if ips:
        out.append({"type": "ioc_ip", "target": "siem", "title": f"{camp['name']} hosting IPs", "content": "\n".join(ips),
                    "confidence": "medium",
                    "false_positive_notes": "IPs on CDNs / shared hosting (Cloudflare, Vercel) will over-block; use with hostnames."})
    yara_s = yara_strings_from([m["features"] for m in members], len(members))
    y = yara_rule(camp, yara_s, kit)
    if y:
        out.append({"type": "yara", "target": "edr", "title": f"YARA: {camp['name']} kit HTML", "content": y, "confidence": conf,
                    "false_positive_notes": "Titles / asset names may appear on the legitimate brand site; test against legitimate HTML first."})
    return out
